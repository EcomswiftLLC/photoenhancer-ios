"""Verifies the App Store copy in docs/store/listing/*.txt and writes docs/store/metadata.md from it.

The .txt files are the single source of truth (paste them into App Store Connect as they are). This script fails
(non-zero exit) if a limit or a rule is broken, so the numbers in metadata.md are always computed, never typed.

Run: python tools/build_store_metadata.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIST = ROOT / "docs/store/listing"
OUT = ROOT / "docs/store/metadata.md"

LIMITS = {"name": 30, "subtitle": 30, "promo": 170, "keywords": 100, "description": 4000, "whats-new": 4000, "review-notes": 4000}
REQUIRED_KEYWORDS = ["ai", "quality", "restore", "colorize", "blurry", "resolution", "denoise"]
COMPETITORS = ["remini", "picwish", "fotor", "vivid", "myheritage", "deep nostalgia", "hitpaw", "vanceai", "topaz",
               "gigapixel", "lightricks", "facetune", "picsart", "snapseed", "vsco", "capcut", "pixelup", "photoroom"]
# Honest-copy rules (docs/DESIGN.md section 8). Clarivo really runs AI models, so "AI" is allowed; these are not.
BANNED = ["best ", "#1", "number one", "award", "5-star", "five star", "guaranteed", "recover lost", "lost detail",
          "restore detail", "reconstruct", "face restoration", "perfect", "magic", "revolutionary", "like new"]
STOP = {"a", "an", "the", "and", "or", "of", "to", "in", "on", "for", "with"}

BASE = "https://ecomswiftllc.github.io/clarivo/"
FALLBACK_NAMES = ["Photo Enhancer HD: Clarix", "Photo Enhancer HD: Crispa", "AI Photo Enhancer: Clarivo"]


def read(n):
    return (LIST / f"{n}.txt").read_text(encoding="utf-8").strip("\r\n")


def words(s):
    return {w for w in re.findall(r"[a-z0-9]+", s.lower()) if w not in STOP}


def stem(w):
    return w[:-1] if w.endswith("s") and len(w) > 3 else w


def check(t):
    errs = []
    for k, lim in LIMITS.items():
        if len(t[k]) > lim:
            errs.append(f"{k}: {len(t[k])} > {lim}")
    if not t["name"].endswith(": Clarivo") or t["name"].count(":") != 1:
        errs.append("name: keywords first, brand last, one colon")
    if "clarivo" in t["subtitle"].lower():
        errs.append("subtitle: the brand is already in the name")
    kw = t["keywords"]
    if " " in kw or kw.endswith(",") or kw.startswith(","):
        errs.append("keywords: no spaces, no stray commas")
    kwl = kw.split(",")
    if len(set(kwl)) != len(kwl):
        errs.append("keywords: repeated keyword")
    for r in REQUIRED_KEYWORDS:
        if r not in kwl:
            errs.append(f"keywords: missing {r}")
    seen = {stem(w) for w in words(t["name"] + " " + t["subtitle"])}
    for w in kwl:
        if stem(w) in seen:
            errs.append(f"keywords: '{w}' already in name or subtitle")
    stems = [stem(w) for w in kwl]
    if len(set(stems)) != len(stems):
        errs.append("keywords: two keywords share a stem")
    blob = " ".join(t.values()).lower()
    for c in COMPETITORS:
        if re.search(rf"\b{c}\b", blob):
            errs.append(f"competitor or third-party brand named: {c}")
    for bad in BANNED:
        if bad in blob:
            errs.append(f"dishonest or unprovable wording: {bad.strip()}")
    if "never uploaded" not in t["description"]:
        errs.append("description must carry the privacy line (never uploaded)")
    return errs


def main():
    t = {k: read(k) for k in LIMITS}
    errs = check(t)
    if errs:
        print("STORE COPY CHECK FAILED")
        for e in errs:
            print(" -", e)
        sys.exit(1)

    def n(k):
        return f"{len(t[k])} of {LIMITS[k]}"

    fallbacks = "; ".join(f'"{x}" ({len(x)})' for x in FALLBACK_NAMES)
    md = f"""# Clarivo: App Store listing (en-US)

Generated by `python tools/build_store_metadata.py` from `docs/store/listing/*.txt`. Edit those files, not this one.
Naming rule (owner, always): search keywords first, brand last, one colon. The check script enforced every number below.

| Field | Value | Characters |
|---|---|---|
| Name | {t['name']} | {n('name')} |
| Subtitle | {t['subtitle']} | {n('subtitle')} |
| Home screen name | Clarivo | |
| Promotional text | see below | {n('promo')} |
| Keywords | {t['keywords']} | {n('keywords')} |
| Description | see below | {n('description')} |
| What's New (1.0) | see below | {n('whats-new')} |
| Primary category | Photo & Video | |
| Secondary category | Graphics & Design | |
| Price | Free with ads (AdMob banner on Home + rewarded ad before save/share, free when no ad is available), no IAP | |
| Bundle id | com.ecomswift.photoenhancer | |
| Copyright | 2026 Ecom Swift LLC | |
| Support URL | {BASE}support/ | |
| Marketing URL | {BASE} | |
| Privacy Policy URL | {BASE}privacy/ | |
| Terms of Use | {BASE}terms/ (linked at the end of the description; Apple's standard EULA applies) | |
| Platforms | iPhone and iPad (universal), iOS 17.0 or later | |

Fallback names if Apple says "{t['name']}" is taken: {fallbacks}. Keep the keywords-first, brand-last pattern.

Keyword field rules, checked by code: no word repeated from the name or subtitle (photo, enhancer, hd, unblur, upscale and
sharpen are already indexed), no spaces, no repeated stem, no other app's brand. Apple combines name, subtitle and keyword
words, so searches such as "ai photo enhancer", "photo quality", "old photo restore", "colorize photo", "fix blurry
picture", "increase resolution", "4k upscale" and "clear photo" are covered.

## Promotional text ({n('promo')})

```
{t['promo']}
```

## Description ({n('description')})

Honest wording (docs/DESIGN.md section 8): enhance, sharpen, upscale; never "recover lost detail" or face reconstruction;
the heavy-blur limit and the ad model are stated plainly; no star or review claims, no competitor names.

```
{t['description']}
```

Facts behind the wording (re-verify against the shipped build before every submission and edit the copy if a feature was
cut or renamed): 2x/4x/8x, 8x capped at 8192 px long side and 48 MP with a notice (docs/ARCHITECTURE.md feature 1);
tiled processing; NAFNet deblur plus Core Image sharpen; super-resolution supersample denoise with strength; Vision face
crops plus super-resolution (no generative face model); DDColor colorize on the full-resolution L channel; classical
restore (scratch/dust, fade, de-yellow); auto fix; compare slider with synced zoom and hold-for-original; batch with
per-item progress and cancel, one ad per batch; JPG/PNG/HEIC, size options, quality slider, EXIF keep/strip including GPS;
Photos/Files/Share, no watermark; only NSPhotoLibraryAddUsageDescription; rewarded grace 120 s. If a model is missing from
the release build, remove its AI claim before submitting.

## What's New, version 1.0 ({n('whats-new')})

```
{t['whats-new']}
```

## App Review notes ({n('review-notes')})

```
{t['review-notes']}
```

Contact for review (App Store Connect form): the owner's name, phone and the support address. Sign-in required: No.

## Age rating answers (Apple's questionnaire)

Expected result: 4+.

- In-app controls: Parental Controls No. Age Assurance No.
- Unrestricted Web Access: No. User-Generated Content: No. Messaging and Chat: No. Advertising: Yes (Google AdMob).
- Content descriptors: all None. Health or Wellness Topics: No. Gambling and contests: No.
- In AdMob set the maximum ad content rating to General (or Parental Guidance) and block sensitive categories.

## App Privacy (nutrition label)

See `docs/store/app-privacy.md`. Summary: tracking Yes (Device ID, Advertising Data); Product Interaction and Performance
Data collected and linked, not used for tracking; Coarse Location and Crash Data not linked. Photos are NOT collected.

## Export compliance and other forms

- Encryption: only HTTPS through system and SDK networking (exempt). `ITSAppUsesNonExemptEncryption` = NO in Info.plist.
- Content rights: sample photos from Pexels (Pexels License) and The Met Open Access (CC0), see
  `docs/store/photo-credits.md`. Answer Yes to "contains third-party content" with the right to use it.
- Digital Services Act trader status: Ecom Swift LLC as a trader.

## Screenshots

`python tools/make_store_shots.py <CI store-iphone folder> design/store/iphone69` (6.9-inch, 1320 x 2868) and
`python tools/make_store_shots_ipad.py <CI store-ipad folder> design/store/ipad13` (13-inch iPad, 2064 x 2752).
Slides use real captures only; missing captures are skipped. Slide copy is in `tools/store_shots_common.py`.

## Localisation

Drafts for es, fr, de and zh-Hans: `docs/store/metadata-localized.md`.
"""
    OUT.write_text(md, encoding="utf-8")
    print("store copy OK")
    for k in LIMITS:
        print(f"  {k}: {len(t[k])}/{LIMITS[k]}")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
